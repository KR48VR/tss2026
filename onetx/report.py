"""Write docs/REPORT.md: a plain-language summary of what the processed tables say."""
from __future__ import annotations

import json

import pandas as pd

from .config import PROCESSED, ROOT
from .io import load


def _md(df: pd.DataFrame, cols: list[str], n: int = 15, floatfmt: int = 2) -> str:
    d = df[cols].head(n).copy()
    for c in d.columns:
        if d[c].dtype.kind == "f":
            d[c] = d[c].round(floatfmt)
    return d.to_markdown(index=False)


def write_report(path=None) -> str:
    path = path or ROOT / "docs" / "REPORT.md"
    stats = json.loads((PROCESSED / "build_stats.json").read_text())
    tf = load("frontier_tasks"); occ = load("frontier_occupations"); act = load("frontier_activities"); sk = load("frontier_skills")
    ssoc = load("frontier_ssoc2024"); roles = load("frontier_sfw_roles"); fc = load("forecast_tasks")
    focc = load("forecast_occupations"); fssoc = load("forecast_ssoc2024"); frole = load("forecast_sfw_roles"); fsk = load("forecast_skills")
    metr = load("ai_metr_horizons")
    L = []
    L.append("# What the data say (auto-generated by `python -m onetx report`)\n")
    L.append(f"Built with 'today' = {stats['now']}. Every number below is a planning signal with a range, not a prediction of job loss.\n")
    L.append("## 1. Coverage\n")
    cc = stats["crosswalk_counts"]
    L.append(f"- O*NET occupations: {cc['onet_occupations']}; tasks: {len(tf):,}; activities (DWA/IWA/GWA): {len(act):,}.")
    L.append(f"- O*NET -> ISCO-08 pairs: {cc['onet_isco_pairs']:,}; O*NET -> SSOC 2024 pairs: {cc['onet_ssoc_pairs']:,} covering {cc['ssoc_covered']} of 1,006 SSOC occupations.")
    L.append(f"- Skills Framework roles linked to SSOC: {cc['sfw_roles']} (of which {cc['sfw_roles_from_singstat']} carry SingStat's own code; the rest use the text matcher, whose hold-out accuracy is top-1 {stats['role_text_matcher_eval']['top1_5digit']:.0%}, top-5 {stats['role_text_matcher_eval']['top5_5digit']:.0%}).")
    sc = stats["task_status_counts"]
    L.append(f"- Task status: {sc.get('observed_automation',0):,} observed with AI mostly doing the task, {sc.get('observed_augmentation',0):,} observed with AI mostly helping, {sc.get('physical_robotics',0):,} physical (robotics signal), {sc.get('not_observed',0):,} not observed in Claude usage data.\n")
    L.append("## 2. The capability frontier (METR time horizons, re-fitted here)\n")
    metr = metr.assign(release_date=pd.to_datetime(metr.release_date).dt.strftime("%Y-%m-%d"))
    L.append(_md(metr.sort_values("release_date", ascending=False), ["alias", "release_date", "horizon50_min", "horizon80_min"], n=8, floatfmt=0))
    t = stats["metr_trend"]
    L.append(f"\nFrontier doubling time since 2024 (our fit): about {t['doubling_days']:.0f} days. Forecast parameters: {json.dumps(stats['forecast_params'])}\n")
    L.append("## 3. Where AI usage is concentrated today\n")
    L.append("### Most-used O*NET tasks (share of Claude.ai conversations, Apr-May 2026)\n")
    L.append(_md(tf.sort_values("usage_latest", ascending=False), ["task_id", "onet_soc_code", "task_statement", "usage_latest", "automation_share", "ai_autonomy", "human_only_hours"], n=15))
    L.append("\n### Generalized work activities ranked by observed automation\n")
    L.append(_md(act[act.level == "gwa"].sort_values("observed_automation", ascending=False), ["activity_id", "name", "n_tasks", "share_tasks_observed", "observed_automation", "ms_share"], n=12))
    L.append("\n### O*NET occupations ranked by observed automation (task-weighted)\n")
    L.append(_md(occ.sort_values("observed_automation", ascending=False), ["onet_soc_code", "title", "share_weight_observed", "observed_automation", "aei_job_exposure", "ai_applicability_score", "robot_exposure_index"], n=20))
    L.append("\n### Singapore SSOC 2024 occupations ranked by observed automation (pulled through the crosswalk)\n")
    L.append(_md(ssoc.sort_values("observed_automation", ascending=False), ["ssoc_code", "ssoc_title", "n_onet_occupations", "share_weight_observed", "observed_automation", "ai_applicability_score"], n=20))
    L.append("\n### Skills Framework roles ranked by observed automation via their key tasks\n")
    L.append(_md(roles.sort_values("observed_automation_via_tasks", ascending=False), ["sector", "job_role", "n_key_tasks", "share_key_tasks_observed", "observed_automation_via_tasks", "observed_automation_via_ssoc", "mean_match_score"], n=20))
    L.append("\n### O*NET skills ranked by observed automation of the occupations that need them\n")
    L.append(_md(sk[sk.family == "skill"].sort_values("via_occupations_observed_automation", ascending=False), ["element_name", "n_occupations", "via_occupations_observed_automation", "via_activities_observed_automation"], n=15))
    L.append("\n## 4. Timing (central estimate = year by which half of a job's task weight is 'disruptable')\n")
    L.append(f"Task timing buckets (central): {json.dumps(stats['forecast_buckets'])}\n")
    L.append("### O*NET occupations: earliest half-way years\n")
    L.append(_md(focc.sort_values(["half_year_p50", "half_year_p90"]), ["onet_soc_code", "title", "share_by_2028", "share_by_2030", "share_by_2035", "half_year_p10", "half_year_p50", "half_year_p90"], n=20, floatfmt=1))
    L.append("\n### O*NET occupations: latest half-way years (most insulated)\n")
    L.append(_md(focc.sort_values(["half_year_p50", "half_year_p90"], ascending=False), ["onet_soc_code", "title", "share_by_2030", "share_by_2035", "share_beyond_horizon", "half_year_p50", "half_year_p90"], n=15, floatfmt=1))
    L.append("\n### Singapore SSOC 2024: earliest half-way years\n")
    L.append(_md(fssoc.sort_values(["half_year_p50", "half_year_p90"]), ["ssoc_code", "ssoc_title", "share_by_2028", "share_by_2030", "share_by_2035", "half_year_p10", "half_year_p50", "half_year_p90"], n=20, floatfmt=1))
    L.append("\n### Skills Framework roles: earliest half-way years (via key tasks)\n")
    L.append(_md(frole.sort_values(["half_year_p50", "half_year_p90"]), ["sector", "job_role", "n_tasks", "share_by_2028", "share_by_2030", "half_year_p10", "half_year_p50", "half_year_p90"], n=20, floatfmt=1))
    L.append("\n### O*NET skills: half-way years\n")
    L.append(_md(fsk[fsk.family == "skill"].sort_values(["half_year_p50"]), ["element_name", "n_occupations", "share_by_2028", "share_by_2030", "share_by_2035", "half_year_p50", "half_year_p90"], n=20, floatfmt=1))
    L.append("\n## 5. Read this before using the numbers\n")
    L.append("- Usage data come from one provider (Anthropic) and reflect who uses Claude, not the whole economy. Microsoft's Copilot figures are a second opinion at the activity level.")
    L.append("- 'Observed automation' means that when the task shows up in AI usage, the AI is mostly doing it rather than helping. It says nothing about how many of the task's real-world instances involve AI.")
    L.append("- Timing combines a capability trend (METR) with an explicit adoption lag. Change the parameters in `onetx.forecast.ForecastParams` and rebuild; the ranges (p10/p90) are the honest output.")
    L.append("- Singapore links are official where SingStat coded them (SSOC-ISCO tables, SFw role tags) and text-matched elsewhere; every text match carries a score you can filter on.")
    text = "\n".join(L) + "\n"
    path.write_text(text)
    return text
